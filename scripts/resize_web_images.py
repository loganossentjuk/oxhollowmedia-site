#!/usr/bin/env python3
"""
Make the site's display photos light. Web copies only: print files come from
Dropbox (scripts/gelato_publish.py) and are never touched here.

For every images/portfolio/**/<name>.jpg (already watermarked by watermark.py):
  <name>.webp      long edge <= 2000 and width <= 1600, WebP q75 (q70 if > 350 KB)
  <name>-800.webp  800 px wide, WebP q72 (for srcset on phones and grids)
  <name>.jpg       same size as <name>.webp, progressive JPEG q80 (fallback)
Never upscales. The baked-in watermark is kept (we resample the stamped JPG);
every output is recorded in images/portfolio/.watermarked.json so watermark.py
won't stamp it again.

Then it rewrites markup so layout and srcset match the new files:
  - hand-written pages: <source type="image/webp" srcset="X.webp"> becomes
    srcset="X-800.webp 800w, X.webp <W>w" sizes="...", and the <img width/height>
  - prints/catalog.json width/height (build_print_pages.py reads these)
Run build_print_pages.py afterwards for the print pages.

    python3 scripts/resize_web_images.py           # images not yet done + markup
    python3 scripts/resize_web_images.py --force   # redo every image
Needs Pillow with WebP support.

Order for new photos: drop in <name>.jpg, run watermark.py, then this script.
"""
import hashlib, json, re, sys
from pathlib import Path
from PIL import Image, features

ROOT = Path(__file__).resolve().parent.parent
PORTFOLIO = ROOT / "images" / "portfolio"
LEDGER = PORTFOLIO / ".watermarked.json"
CATALOG = ROOT / "prints" / "catalog.json"
MAX_W, MAX_LONG, SMALL_W = 1600, 2000, 800
TARGET = 350 * 1024
GRID_SIZES = "(max-width: 600px) 100vw, 33vw"
# pages with portfolio <picture>s; the print pages and the shop grid in
# prints/index.html are generated by build_print_pages.py
PAGES = ["index.html", "gallery.html", "about.html", "events.html", "work-with-me.html",
         "films.html", "filmmaking.html"]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def target_size(w, h):
    s = min(1.0, MAX_W / w, MAX_LONG / max(w, h))
    return (w, h) if s == 1.0 else (round(w * s), round(h * s))


def process(jpg):
    im = Image.open(jpg)
    im.load()
    icc = im.info.get("icc_profile")
    im = im.convert("RGB")
    size = target_size(*im.size)
    big = im if size == im.size else im.resize(size, Image.LANCZOS)
    webp = jpg.with_suffix(".webp")
    for q in (75, 70):
        big.save(webp, "WEBP", quality=q, method=6, icc_profile=icc)
        if webp.stat().st_size <= TARGET:
            break
    sw = min(SMALL_W, size[0])
    small = big.resize((sw, round(size[1] * sw / size[0])), Image.LANCZOS)
    small.save(jpg.with_name(jpg.stem + "-800.webp"), "WEBP", quality=72, method=6, icc_profile=icc)
    big.save(jpg, "JPEG", quality=80, optimize=True, progressive=True, icc_profile=icc)
    return size, q


def resize_all(force):
    if not features.check("webp"):
        sys.exit("Pillow has no WebP support")
    ledger = json.loads(LEDGER.read_text()) if LEDGER.exists() else {}
    done = 0
    for jpg in sorted(PORTFOLIO.rglob("*.jpg")):
        small = jpg.with_name(jpg.stem + "-800.webp")
        if small.exists() and not force:
            continue
        (w, h), q = process(jpg)
        done += 1
        for f in (jpg, jpg.with_suffix(".webp"), small):
            ledger[str(f.relative_to(ROOT))] = sha(f)
        print(f"{jpg.relative_to(ROOT)}  {w}x{h}  webp q{q}")
    LEDGER.write_text(json.dumps(ledger, indent=1, sort_keys=True) + "\n")
    print(f"{done} image(s) resized")


def dims(rel):
    with Image.open(ROOT / rel.lstrip("/")) as im:
        return im.size


PIC = re.compile(r'<source type="image/webp" srcset="([^"\s]+)\.webp"(?: sizes="[^"]*")?>'
                 r'<img src="([^"]+\.jpg)" width="\d+" height="\d+"')


def rewrite(m, sizes):
    stem, jpg = m.group(1), m.group(2)
    if not (ROOT / (stem.lstrip("/") + "-800.webp")).exists():
        return m.group(0)
    w, h = dims(jpg)
    return (f'<source type="image/webp" srcset="{stem}-800.webp 800w, {stem}.webp {w}w" sizes="{sizes}">'
            f'<img src="{jpg}" width="{w}" height="{h}"')


def update_markup():
    for name in PAGES:
        page = ROOT / name
        if not page.exists():
            continue
        old = page.read_text()
        new = PIC.sub(lambda m: rewrite(m, GRID_SIZES), old)
        if new != old:
            page.write_text(new)
            print(f"updated {name}")
    cat = json.loads(CATALOG.read_text())
    changed = 0
    for p in cat["prints"]:
        w, h = dims(p["image"])
        if (p["width"], p["height"]) != (w, h):
            p["width"], p["height"] = w, h
            changed += 1
    if changed:
        CATALOG.write_text(json.dumps(cat, indent=2, ensure_ascii=False) + "\n")
    print(f"catalog: {changed} print size(s) updated")


if __name__ == "__main__":
    resize_all("--force" in sys.argv)
    update_markup()
